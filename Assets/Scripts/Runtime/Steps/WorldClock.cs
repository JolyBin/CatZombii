using System;

namespace Core.Steps
{
    /// <summary>
    /// Всё, что живёт по ТАКТАМ МИРА, а не по секундам, реализует этот интерфейс
    /// и получает <see cref="Tick"/> строго от <see cref="WorldClock"/>.
    /// Ни одна система не имеет права заводить собственный цикл ожидания:
    /// в пошаговой игре время создаёт только игрок.
    /// </summary>
    public interface ITickable
    {
        void Tick();
    }

    /// <summary>
    /// ЧАСЫ МИРА — единственный источник времени пошаговой игры (docs/10 §0.2).
    ///
    /// Такт мира = одно действие игрока. Действий ровно два:
    ///   1) ПЕРЕЛИВ шарика между колбами (<see cref="Core.Flask.FlaskController.MoveCommand"/>);
    ///   2) ВАРКА, то есть нажатие кнопки котла (<see cref="Core.Spells.TableController.OnBrewCommand"/>).
    /// Не двигается игрок — мир стоит. Отсюда и берётся цена сортировки: каждый перелив
    /// оплачен ходом соседей, а длинный рецепт дорожает сам, без единого таймера.
    ///
    /// Подписки на эти два события живут в <see cref="StepsController"/> — «часы» намеренно
    /// не знают ни про колбы, ни про котёл, ни про бой, только про <see cref="ITickable"/>.
    /// Зато порядок обработки такта виден целиком в одном методе <see cref="Tick"/>
    /// и не зависит от того, в каком порядке кто на что подписался.
    /// </summary>
    public sealed class WorldClock
    {
        // =====================================================================================
        // ЕДИНСТВЕННЫЙ МНОЖИТЕЛЬ КОНВЕРСИИ «миллисекунды -> такты».
        //
        // Все длительности прототипа записаны в ассетах в миллисекундах (кулдауны врагов,
        // фазы босса, спавн, стан). Переписывать ассеты до замера нельзя: конверсионная
        // константа «сколько переливов приходится на одно схлопывание» ЕЩЁ НЕ ЗАМЕРЕНА —
        // её снимает TactMeter (docs/10 §8, шаг 0, вторая метрика).
        //
        // Поэтому стартовые значения в тактах выводятся отсюда, и после замера правится
        // РОВНО ЭТО ЧИСЛО — все враги, фазы босса и стан переедут вместе с ним.
        //
        // Почему 1000, а не 5000 из docs/10 §0.2: там конверсия посчитана по такту
        // СХЛОПЫВАНИЯ (5,0 с), а единица пошагового мира — ПЕРЕЛИВ. Схлопывание стоит
        // нескольких переливов, поэтому такт-перелив в несколько раз короче, и при 5000
        // все враги слипались в одно значение (сам документ это и отмечает как ошибку).
        // 1000 мс на перелив даёт: Simple 4000 -> 4, Rat 1500 -> 2, Power 5000 -> 5,
        // Boss 5000/3500/2500 -> 5/4/3 — то есть враги РАЗНЕСЕНЫ, чего и требует И1.5.
        //
        // Разнести конкретного врага отдельно от общего множителя можно, не трогая это
        // число: у UnitConfig есть поле-override в тактах (см. UnitConfig.AttackCooldownTacts).
        // =====================================================================================
        public const int MILLISECONDS_PER_TACT = 1000;

        /// <summary>
        /// Сколько тактов прожил мир с начала боя. Растёт только от действий игрока.
        /// </summary>
        public int Tacts { get; private set; }

        private readonly ITickable _cauldron;
        private readonly ITickable _battle;

        private bool _isRunning;

        public WorldClock(ITickable cauldron, ITickable battle)
        {
            _cauldron = cauldron;
            _battle = battle;
        }

        /// <summary>
        /// Старая длительность в миллисекундах -> такты. Меньше одного такта не бывает:
        /// «ноль тактов» означал бы бесплатное действие, то есть возврат к real-time.
        /// Ноль на входе — это «не атакует вовсе», он так и остаётся нулём.
        /// </summary>
        public static int TactsFromMilliseconds(int milliseconds)
        {
            if (milliseconds <= 0)
                return 0;
            int tacts = (int)Math.Round((double)milliseconds / MILLISECONDS_PER_TACT, MidpointRounding.AwayFromZero);
            return Math.Max(1, tacts);
        }

        /// <summary>Тот же перевод для длительностей, записанных в ассетах в секундах (стан).</summary>
        public static int TactsFromSeconds(int seconds) => TactsFromMilliseconds(seconds * 1000);

        public void Start()
        {
            Tacts = 0;
            _isRunning = true;
        }

        /// <summary>
        /// Часы встали: мир больше не принимает действия игрока. Зовётся на окнах итога
        /// вместе с блокировкой ввода — вторая половина бага №12.
        /// </summary>
        public void Stop() => _isRunning = false;

        /// <summary>
        /// ОДИН ТАКТ МИРА. Порядок фаз задан здесь и только здесь.
        ///
        /// 1) ЧАСЫ КОТЛА. Остывание — прямое последствие действия игрока для его же
        ///    ресурса, поэтому разрешается первым: соседи ходят уже по окончательному
        ///    состоянию котла, а не по промежуточному.
        /// 2) БОЙ. Кулдауны и атаки идут вторыми по одной жёсткой причине: только бой
        ///    умеет ЗАКОНЧИТЬ партию (смерть героя, смерть последнего врага волны).
        ///    Внутри такта после события конца боя не должно происходить ничего — иначе
        ///    хвост котла отваливался бы уже из-под показанного окна итога.
        ///
        /// Почему это НЕ мешает «успеть сварить в последний ход»: варка сначала применяет
        /// заклинание и очищает котёл (TableController.CheckRepit) и только потом просит
        /// такт. К фазе 1 котёл уже пуст, к фазе 2 зелье уже подействовало — значит
        /// такт, которым игрок ПЛАТИТ за варку, не может ни сжечь варящийся рецепт,
        /// ни убить героя раньше только что выпитого лечения. Цена берётся после награды.
        /// </summary>
        public void Tick()
        {
            if (!_isRunning)
                return;

            Tacts++;

            _cauldron?.Tick();
            _battle?.Tick();
        }
    }
}
