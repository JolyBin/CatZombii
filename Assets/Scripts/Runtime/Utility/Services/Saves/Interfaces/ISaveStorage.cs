using System.Threading;
using Cysharp.Threading.Tasks;

namespace Utility.Services.Saves
{
    /// <summary>
    /// КУДА кладётся сейв. Ровно та же развилка, что у языка (<c>ILanguageSource</c>):
    /// модель и сериализация общие, а носитель — платформенный, и живёт за интерфейсом.
    ///
    /// Требование docs/09 (строки 226-229): в игровом коде ноль ссылок на SDK, иначе
    /// выход на мобилки и Steam дорожает. Поэтому игровой код знает только
    /// <see cref="ISaveService"/>; облако Яндекса — ОДНА ИЗ реализаций этого интерфейса,
    /// она лежит в отдельном файле за <c>#if</c> и, когда плагина нет, отсутствует в сборке.
    /// Удаление файла реализации не ломает ничего, кроме самой этой реализации.
    ///
    /// ПОЧЕМУ АСИНХРОННЫЙ, хотя первая реализация (PlayerPrefs) отвечает мгновенно.
    /// Потому что вторая — нет. Облачное сохранение площадки асинхронно по своей природе,
    /// а <c>PlayerPrefs</c> в WebGL пишет не в файл, а в IndexedDB, и флаш туда браузер
    /// делает сам, когда сочтёт нужным. Синхронный интерфейс пришлось бы ломать ровно
    /// в тот день, когда включат облако, — то есть в день, когда сейвы уже у живых игроков.
    /// Заводить его синхронным «пока проще» значит платить за это позже и дороже.
    /// </summary>
    public interface ISaveStorage
    {
        /// <summary>Имя носителя — печатается в лог, чтобы «откуда взялся этот прогресс» отвечалось без отладчика.</summary>
        string Name { get; }

        /// <summary>
        /// Есть ли этот носитель в ЭТОЙ сборке. Проверка компиляционная, а не сетевая:
        /// «SDK ещё не поднялся» — не повод пропускать облако, это повод его подождать,
        /// и ожидание живёт внутри <see cref="LoadAsync"/>, а не здесь.
        /// </summary>
        bool IsAvailable { get; }

        /// <summary>
        /// Прочитать сырой JSON. Пустая строка (или <c>null</c>) — ШТАТНЫЙ ответ «здесь пусто»:
        /// первый запуск игры выглядит именно так и ошибкой не является.
        /// Реализация обязана не бросать: любой сбой носителя гасится внутри и логируется.
        /// </summary>
        UniTask<string> LoadAsync(CancellationToken token);

        /// <summary>Записать сырой JSON. <c>false</c> — не записалось; ронять игру запрещено.</summary>
        UniTask<bool> SaveAsync(string json, CancellationToken token);

        /// <summary>Стереть сейв. Нужно откату к новому профилю и редакторной проверке.</summary>
        UniTask<bool> DeleteAsync(CancellationToken token);
    }
}
