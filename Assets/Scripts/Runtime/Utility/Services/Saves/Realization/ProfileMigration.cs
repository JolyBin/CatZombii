using UnityEngine;

namespace Utility.Services.Saves
{
    /// <summary>
    /// ПУТЬ ОТ СТАРОГО ФОРМАТА К ТЕКУЩЕМУ. Ступеньками по одной версии: v1→v2, v2→v3, …
    ///
    /// Почему ступеньками, а не «прочитать что получится и забыть». Прыжок «из любой версии
    /// сразу в текущую» пишется один раз, а потом обязан помнить все промежуточные формы —
    /// то есть превращается в кучу <c>if</c>, которую никто не в состоянии проверить.
    /// Ступенька же проверяется целиком: у неё один вход и один выход.
    ///
    /// Правило на будущее: МЕНЯЕШЬ СМЫСЛ ИЛИ ИМЯ ПОЛЯ — поднимаешь
    /// <see cref="PlayerProfile.CURRENT_VERSION"/> и дописываешь <c>case</c>
    /// в <see cref="TryMigrateStep"/>. ДОБАВЛЯЕШЬ новое поле — версию поднимать НЕ надо:
    /// <c>JsonUtility</c> оставит в нём значение по умолчанию, и это ровно то, что нужно
    /// (у старого игрока новой сущности и не было).
    ///
    /// Первая ступенька появилась вместе с метой (v1 → v2, docs/10 §13) — ровно тот
    /// день, ради которого механизм и заводился: без него сейвы всех, кто уже играл,
    /// стали бы мусором молча.
    /// </summary>
    public static class ProfileMigration
    {
        /// <summary>Страховка от ступеньки, которая не двигает версию: вечный цикл на старте игры хуже потерянного сейва.</summary>
        private const int MAX_STEPS = 64;

        /// <summary>
        /// Поднять профиль до текущей версии. <c>false</c> — путь неизвестен; вызывающий
        /// обязан откатиться к новому профилю, а не пытаться играть на полупонятых данных.
        /// </summary>
        public static bool TryMigrate(PlayerProfile profile, out string error)
        {
            error = null;

            if (profile == null)
            {
                error = "профиль пуст";
                return false;
            }

            if (profile.Version > PlayerProfile.CURRENT_VERSION)
            {
                // Сейв из БОЛЕЕ НОВОЙ сборки. Живой сценарий — откат релиза на площадке.
                // Читать его «как получится» нельзя: незнакомые поля мы молча потеряем
                // и при следующем сохранении затрём. Честнее начать заново, чем испортить.
                error = $"сейв версии {profile.Version} новее, чем понимает игра ({PlayerProfile.CURRENT_VERSION})";
                return false;
            }

            int steps = 0;
            while (profile.Version < PlayerProfile.CURRENT_VERSION)
            {
                int from = profile.Version;

                if (!TryMigrateStep(profile, from, out error))
                    return false;

                if (profile.Version <= from || ++steps > MAX_STEPS)
                {
                    error = $"миграция с версии {from} не подняла версию";
                    return false;
                }

                Debug.Log($"[Saves] Сейв смигрирован: v{from} → v{profile.Version}.");
            }

            return true;
        }

        /// <summary>
        /// Одна ступенька: привести профиль версии <paramref name="from"/> к версии
        /// <c>from + 1</c> и записать новую версию в <see cref="PlayerProfile.Version"/>.
        /// </summary>
        private static bool TryMigrateStep(PlayerProfile profile, int from, out string error)
        {
            switch (from)
            {
                // ───────────────────────────────────────────────────────────────────────
                // v1 → v2: МЕТА (docs/10 §13). Что именно поменялось в смысле полей:
                //
                // 1. «Текущего уровня» больше нет. Узлы карты стали ПЕРЕПРОХОДИМЫМИ
                //    (§13.4), поэтому LevelIndex («на каком уровне игрок стоит») сменился
                //    на ClearedNodes («сколько узлов пройдено»). Числа совпадают: в v1
                //    LevelIndex рос ровно на победу, то есть уже был счётчиком пройденного.
                //
                //    ⚠️ Известная неточность на единицу, и она сознательная. В v1
                //    HomeController.AddConfigIndex() упирался в последний уровень
                //    и НЕ инкрементировался — это и был тот самый тупик, ради которого
                //    затевалась перепроходимость. Значит у игрока, добившего последний
                //    уровень, в сейве всё равно стоит «пройдено на один меньше».
                //    Отличить его от того, кто стоит перед последним уровнем и не прошёл
                //    его, данные v1 не позволяют В ПРИНЦИПЕ. Выбран щадящий вариант:
                //    последний узел считается непройденным. Цена — один повтор боя,
                //    который игрок и так может перепройти; альтернатива (подарить
                //    прохождение) выдала бы награду за бой, которого могло не быть.
                //
                // 2. Слоты колоды у v1-игрока отсутствуют как поле. Выдаём стартовые
                //    четыре (§14.4) явно, а не инициализатором поля: инициализаторы
                //    в профиле запрещены (см. PlayerProfile).
                //
                // 3. Колода и покупки не восстанавливаются и не выдумываются: в v1
                //    покупать было нечего. Пустая запись героя означает «стартовую
                //    колоду ещё не выдавали», и HeroLoadout выдаст её при первом входе
                //    в экран — то есть v1-игрок получит ровно то же, что новый.
                //
                // 4. Выбранного героя добавляем в открытые. Сегодня все книги открыты
                //    (Book.UnlockChapter = 0), но когда геймдизайнер расставит главы,
                //    игрок не должен потерять героя, которым уже играл.
                // ───────────────────────────────────────────────────────────────────────
                case 1:
                    profile.ClearedNodes = profile.LevelIndex;
                    profile.LevelIndex = 0;
                    profile.DeckSlots = PlayerProfile.BASE_DECK_SLOTS;
                    if (!string.IsNullOrEmpty(profile.HeroId))
                        profile.UnlockHero(profile.HeroId);
                    profile.Version = 2;
                    error = null;
                    return true;

                default:
                    error = $"нет миграции с версии {from} на {from + 1}";
                    return false;
            }
        }
    }
}
