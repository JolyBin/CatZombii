namespace Utility.Services.Localization
{
    /// <summary>
    /// ОТКУДА берётся текущий язык. Вынесено в отдельный интерфейс ровно ради
    /// требования docs/09: SDK-слой обязан быть изолированным, иначе выход
    /// на мобилки и Steam дорожает.
    ///
    /// Игровой код не знает ни про PluginYG, ни про Яндекс.Игры — он знает только
    /// про <see cref="ILocalizationService"/>. PluginYG — ОДИН ИЗ источников,
    /// он живёт в отдельном файле за <c>#if</c> и, когда плагина нет,
    /// просто отсутствует в сборке.
    /// </summary>
    public interface ILanguageSource
    {
        /// <summary>Имя источника — печатается в лог при выборе языка, чтобы «почему английский» отвечалось без отладчика.</summary>
        string Name { get; }

        /// <summary>
        /// Вернуть язык, если этот источник его знает. False — источник молчит,
        /// спрашиваем следующий. Молчание — штатный ответ, а не ошибка:
        /// в редакторе SDK не отвечает никогда.
        /// </summary>
        bool TryGetLanguage(out GameLanguage language);
    }
}
