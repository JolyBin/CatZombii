using System;
using Utility.Services.UI;

namespace Meta.UI
{
    /// <summary>
    /// ОБЩЕЕ У ТРЁХ ЭКРАНОВ МЕТЫ — карты, колоды и лавки. Сегодня общее ровно одно:
    /// ПОКАЗ ОТКАЗА.
    ///
    /// ═══ ЗАЧЕМ ═══
    ///
    /// Законы колоды (docs/10 §13.2) отказывают часто и по-разному: «сначала возьми
    /// префикс», «нет свободного слота», «не по карману». Формулировки давно написаны
    /// и локализованы (<c>HeroLoadout.Describe</c>), но уходили только в консоль —
    /// то есть игрок видел, что карточка не надевается, и не понимал почему.
    /// Молчаливый отказ читается как поломка, а не как правило.
    ///
    /// ═══ ПОЧЕМУ ЗДЕСЬ БОЛЬШЕ НЕТ СВОЕЙ ПОЛОСЫ ═══
    ///
    /// Была. В проекте одновременно жили ДВЕ почти одинаковые полосы: эта и
    /// <see cref="UINotice"/>, выросшая из неё копированием (у автора второй не было
    /// доступа к <c>Meta/UI</c>). Две копии одного виджета расходятся молча: правку
    /// цвета, высоты или порядка детей делают в одной, а игрок видит обе.
    ///
    /// Теперь полоса ровно одна — <see cref="UINotice"/>, — а этот класс держит её
    /// экземпляр и отдаёт наследникам прежний, ничего не знающий о ней метод
    /// <see cref="SetRefusal"/>. Экраны меты не переписывались вовсе.
    ///
    /// Почему полоса всё ещё СТРОИТСЯ КОДОМ, а не лежит в сцене, — разобрано
    /// в <see cref="UINotice"/>: поправка П5 (docs/10 §8) считает сценовую работу
    /// главным риском, а <c>[SerializeField]</c>-панель в каждом окне — это ручная
    /// привязка, без которой фича не работает МОЛЧА.
    /// </summary>
    public abstract class UIMetaWindow : UIWindow
    {
        /// <summary>
        /// Полоса «почему нельзя». Одна на окно и на всю его жизнь: она держит
        /// созданный кодом объект, поэтому разбирается в <see cref="OnDestroy"/>,
        /// а на закрытие окна только гаснет.
        /// </summary>
        private readonly UINotice _notice = new UINotice();

        /// <summary>
        /// ПОКАЗАТЬ ИЛИ СПРЯТАТЬ ОТКАЗ. Зовётся из <c>Init(model)</c> каждого экрана
        /// значением <c>model.Refusal</c> — в том числе пустым, и это не формальность:
        /// пустая строка гасит прошлый отказ, поэтому сообщение живёт ровно до следующей
        /// перерисовки и не переживает ни успешное действие, ни переход на другой экран.
        ///
        /// Полоса создаётся ЛЕНИВО, при первом непустом отказе: у игрока, который ни разу
        /// не ошибся, в иерархии не появится ничего.
        /// </summary>
        protected void SetRefusal(string text) => _notice.Show(this, text);

        /// <summary>
        /// Окно уходит — отказ уходит с ним. Без этого «нет свободного слота» дождался бы
        /// следующего открытия того же экрана и объяснял бы игроку действие, которого
        /// он не делал.
        /// </summary>
        public override void Hide(Action onHide = null)
        {
            _notice.Clear();
            base.Hide(onHide);
        }

        private void OnDestroy() => _notice.ClearAction();
    }
}
